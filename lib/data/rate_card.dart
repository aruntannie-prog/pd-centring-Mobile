// Rate card data from PD NEW RATE CARD PDF

enum MaterialCategory {
  palagai,
  sheets,
  columnBoxes,
  props,
  channelsBeams,
  other,
}

class RateCardItem {
  final String name;
  final MaterialCategory category;
  final String defaultUnit; // "ft" | "pcs" | "nos"
  final Map<int, double> rateByDays; // tier days → rate
  final double? flatRate; // for items with no day tiers

  const RateCardItem({
    required this.name,
    required this.category,
    required this.defaultUnit,
    this.rateByDays = const {},
    this.flatRate,
  });
}

// Day tiers for snapping
const List<int> _tiers = [3, 5, 10, 20, 30];

/// Snap days to nearest tier (e.g. 25 days → 30)
int snapToTier(int days) {
  for (final t in _tiers) {
    if (days <= t) return t;
  }
  return 30;
}

/// Look up rate for a material by name and number of rental days.
/// Returns 0.0 if material not found.
double lookupRate(String materialName, int days) {
  final item = rateCardItems.firstWhere(
    (i) => i.name == materialName,
    orElse: () => const RateCardItem(
        name: '', category: MaterialCategory.other, defaultUnit: 'pcs'),
  );
  if (item.flatRate != null) return item.flatRate!;
  if (item.rateByDays.isEmpty) return 0.0;
  final tier = snapToTier(days);
  return item.rateByDays[tier] ?? item.rateByDays[_tiers.last] ?? 0.0;
}

/// Default unit for a material name
String defaultUnitFor(String materialName) {
  final item = rateCardItems.firstWhere(
    (i) => i.name == materialName,
    orElse: () => const RateCardItem(
        name: '', category: MaterialCategory.other, defaultUnit: 'pcs'),
  );
  return item.defaultUnit;
}

/// Display label for a category
String categoryLabel(MaterialCategory cat) {
  switch (cat) {
    case MaterialCategory.palagai:
      return 'Palagai (Planks)';
    case MaterialCategory.sheets:
      return 'Centring Sheets';
    case MaterialCategory.columnBoxes:
      return 'Column Boxes';
    case MaterialCategory.props:
      return 'Props & Support';
    case MaterialCategory.channelsBeams:
      return 'Channels & Beams';
    case MaterialCategory.other:
      return 'Other';
  }
}

